// ────────────────────────────────────────────────────────
// ⚠️ (2026-09-25) كل خدمات الشحن كانت تكتب:
//     statusHistory[الحالة] = { by: النظام }
// وهذا يمسح اسم الموظف اللي دخّل الطلب لنفس الحالة قبلها. الطلب
// اللي يرجع لحالة سبق ومرّ بيها يضيع صاحبها الأصلي للأبد، وصفحات
// الإحصائيات تقرا السجل فتنسب الطلب للنظام أو للأدمن بدل الموظف.
// هسه ما نكتب فوق أي حالة مسجّلة — ومين غيّر الطلب آخر مرة محفوظ
// بـlastUpdateBy/lastStatusAt اللي موجودين أصلاً.
// (نفس منطق docs/orderCredit.js بالواجهة)
// ════════════════════════════════════════════════════════
export function addHistory(existing = {}, status, by, timeISO) {
  const out = {};
  // ننظّف المفاتيح الرقمية الغلط من بيانات قديمة
  Object.entries(existing || {}).forEach(([k, v]) => { if (isNaN(Number(k))) out[k] = v; });

  let key;
  try { key = encodeURIComponent(status); } catch (e) { key = String(status); }

  // مسجّلة من قبل بأي من الصيغتين؟ نتركها متل ما هي
  if (out[key] || out[status]) return out;

  out[key] = { time: timeISO || new Date().toISOString(), by };
  return out;
}
